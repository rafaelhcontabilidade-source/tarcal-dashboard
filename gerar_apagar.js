const CATS_OPERACIONAL = [
  'Matérias-Primas',
  'Combustível',
  'Fretes e Logística',
  'Manutenção / Peças',
  'Serviços',
  'Seguros',
  'Pedágio',
  'Impostos e Encargos',
  'Outros Operacionais',
];

function parseDate(str) {
  // DD/MM/YYYY → Date
  const [d,m,y] = str.split('/');
  return new Date(Number(y), Number(m)-1, Number(d));
}

function mesVenc(venc) {
  const [d,m,y] = venc.split('/');
  return `${y}-${m.padStart(2,'0')}`;
}

function mesLabel(yyyyMM) {
  const [y, m] = yyyyMM.split('-');
  const mNames = ['Jan','Fev','Mar','Abr','Mai','Jun','Jul','Ago','Set','Out','Nov','Dez'];
  return `${mNames[parseInt(m)-1]}/${y.slice(2)}`;
}

async function main() {
  // ── Lê PDF ──────────────────────────────────────────────────────────────────
  console.log(`📄 Lendo PDF: ${PDF_PATH}`);
  const DADOS = await parsePDF(PDF_PATH);

  // Preenche nome via DePara (ou fallback)
  const DEPARA_NOME = {};
  DEPARA.forEach(([cod, forn]) => { DEPARA_NOME[cod] = forn; });
  DADOS.forEach(r => { r[4] = DEPARA_NOME[r[3]] || ('FORNECEDOR ' + r[3]); });

  // Meses dinâmicos a partir dos vencimentos reais
  const mesesSet = new Set(DADOS.map(r => mesVenc(r[2])));
  const MESES = Array.from(mesesSet).sort();
  const MESES_LABEL = MESES.map(mesLabel);

  console.log(`📊 Lendo Excel: ${XLSX_PATH}`);
  const wb = new ExcelJS.Workbook();
  await wb.xlsx.readFile(XLSX_PATH);

  // ─── Remove abas existentes se houver ──────────────────────────────────────
  ['DePara','APagar','FC_Direto'].forEach(name => {
    const s = wb.getWorksheet(name);
    if (s) wb.removeWorksheet(s.id);
  });

  // ════════════════════════════════════════════════════════════════════════════
  // ABA 1: DePara
  // ════════════════════════════════════════════════════════════════════════════
  const wsDep = wb.addWorksheet('DePara', { properties: { tabColor: { argb: 'FF4472C4' } } });
  wsDep.columns = [
    { header: 'Cod', key: 'cod', width: 10 },
    { header: 'Fornecedor', key: 'forn', width: 45 },
    { header: 'GrupoSint', key: 'grupo', width: 35 },
  ];
  // Style header
  ['A1','B1','C1'].forEach(cell => {
    wsDep.getCell(cell).fill = { type: 'pattern', pattern: 'solid', fgColor: { argb: 'FF4472C4' } };
    wsDep.getCell(cell).font = { bold: true, color: { argb: 'FFFFFFFF' } };
  });
  DEPARA.forEach(([cod, forn, grupo]) => {
    wsDep.addRow({ cod, forn, grupo });
  });
  // Add extra rows for unknown codes found in DADOS (novos fornecedores)
  const knowCods = new Set(DEPARA.map(d=>d[0]));
  const extraCods = new Set();
  DADOS.forEach(r => { if (!knowCods.has(r[3])) extraCods.add(r[3]); });
  extraCods.forEach(cod => {
    const nome = DEPARA_NOME[cod] || ('FORNECEDOR ' + cod);
    wsDep.addRow({ cod, forn: nome, grupo: 'Outros Operacionais' });
  });
  console.log(`✅ DePara: ${wsDep.rowCount-1} fornecedores`);

  // ════════════════════════════════════════════════════════════════════════════
  // ABA 2: APagar
  // ════════════════════════════════════════════════════════════════════════════
  const wsAP = wb.addWorksheet('APagar', { properties: { tabColor: { argb: 'FFED7D31' } } });
  wsAP.columns = [
    { header: 'Documento', key: 'doc', width: 16 },
    { header: 'Emissao', key: 'emis', width: 13 },
    { header: 'Vencimento', key: 'venc', width: 13 },
    { header: 'MesVenc', key: 'mes', width: 10 },
    { header: 'Fornecedor_Cod', key: 'cod', width: 16 },
    { header: 'Fornecedor_Nome', key: 'nome', width: 45 },
    { header: 'Historico', key: 'hist', width: 40 },
    { header: 'Valor', key: 'valor', width: 16 },
    { header: 'Categoria', key: 'cat', width: 30 },
    { header: 'Tipo', key: 'tipo', width: 12 },
    { header: 'GrupoMae', key: 'grupo', width: 30 },
  ];
  // Header style
  const hRow = wsAP.getRow(1);
  hRow.eachCell(cell => {
    cell.fill = { type: 'pattern', pattern: 'solid', fgColor: { argb: 'FFED7D31' } };
    cell.font = { bold: true, color: { argb: 'FFFFFFFF' } };
  });

  let totalVal = 0;
  DADOS.forEach(([doc, emis, venc, cod, nome, hist, valor], i) => {
    const rowNum = i + 2;
    const cat = getCategoria(cod);
    const grupo = getGrupoMae(cat);
    const mv = mesVenc(venc);
    totalVal += valor;

    const row = wsAP.addRow({
      doc: String(doc), emis, venc, mes: mv,
      cod, nome, hist, valor,
      cat, tipo: 'Previsto', grupo
    });
    row.getCell('valor').numFmt = '#,##0.00';
    if (rowNum % 2 === 0) {
      row.eachCell(cell => {
        cell.fill = { type: 'pattern', pattern: 'solid', fgColor: { argb: 'FFFCE4D6' } };
      });
    }
  });

  // Totals row
  const totRow = wsAP.addRow({
    doc: 'TOTAL', emis: '', venc: '', mes: '',
    cod: '', nome: `${DADOS.length} registros`, hist: '',
    valor: totalVal, cat: '', tipo: '', grupo: ''
  });
  totRow.font = { bold: true };
  totRow.getCell('valor').numFmt = '#,##0.00';
  totRow.getCell('valor').fill = { type: 'pattern', pattern: 'solid', fgColor: { argb: 'FFFFEB9C' } };

  console.log(`✅ APagar: ${DADOS.length} registros | Total: R$ ${totalVal.toLocaleString('pt-BR',{minimumFractionDigits:2})}`);

  // ════════════════════════════════════════════════════════════════════════════
  // ABA 3: FC_Direto (pivot computado em JS, não fórmulas SUMIFS)
  // ════════════════════════════════════════════════════════════════════════════
  const wsFC = wb.addWorksheet('FC_Direto', { properties: { tabColor: { argb: 'FF70AD47' } } });

  // Compute pivot
  const pivot = {}; // cat → mes → total
  DADOS.forEach(([, , venc, cod, , , valor]) => {
    const cat = getCategoria(cod);
    const mv = mesVenc(venc);
    if (!pivot[cat]) pivot[cat] = {};
    pivot[cat][mv] = (pivot[cat][mv] || 0) + valor;
  });

  // Headers
  const fcHeaders = ['Categoria', ...MESES_LABEL, 'TOTAL'];
  const hdrRow = wsFC.addRow(fcHeaders);
  hdrRow.eachCell(cell => {
    cell.fill = { type: 'pattern', pattern: 'solid', fgColor: { argb: 'FF1F4E79' } };
    cell.font = { bold: true, color: { argb: 'FFFFFFFF' } };
    cell.alignment = { horizontal: 'center' };
  });
  wsFC.getColumn(1).width = 35;
  MESES.forEach((_, i) => { wsFC.getColumn(i+2).width = 14; });
  wsFC.getColumn(MESES.length+2).width = 16;

  const numFmt = '#,##0.00';

  function addSection(label, cats, bgColor) {
    // Section header
    const sHdr = wsFC.addRow([label]);
    sHdr.getCell(1).fill = { type: 'pattern', pattern: 'solid', fgColor: { argb: bgColor } };
    sHdr.getCell(1).font = { bold: true, color: { argb: 'FFFFFFFF' } };
    sHdr.getCell(1).alignment = { indent: 0 };

    const sectionTotals = new Array(MESES.length).fill(0);
    cats.forEach(cat => {
      const row = [cat];
      let rowTotal = 0;
      MESES.forEach((m, mi) => {
        const v = (pivot[cat] && pivot[cat][m]) ? pivot[cat][m] : 0;
        row.push(v);
        rowTotal += v;
        sectionTotals[mi] += v;
      });
      row.push(rowTotal);
      const r = wsFC.addRow(row);
      r.getCell(1).alignment = { indent: 2 };
      for (let c = 2; c <= MESES.length+2; c++) {
        r.getCell(c).numFmt = numFmt;
        r.getCell(c).alignment = { horizontal: 'right' };
      }
    });

    // Section total row
    const totals = ['= Total ' + label.replace(/^[^\w]*/, ''), ...sectionTotals, sectionTotals.reduce((a,b)=>a+b,0)];
    const tRow = wsFC.addRow(totals);
    tRow.font = { bold: true };
    tRow.eachCell((cell, colNumber) => {
      cell.fill = { type: 'pattern', pattern: 'solid', fgColor: { argb: 'FFD9E1F2' } };
      if (colNumber > 1) cell.numFmt = numFmt;
    });
    wsFC.addRow([]); // spacer
    return sectionTotals;
  }

  const opTotals = addSection('── SAÍDAS OPERACIONAIS', CATS_OPERACIONAL, 'FF2E75B6');
  const empTotals = addSection('── EMPRÉSTIMOS / FINANCIAMENTOS', ['Empréstimos / Financiamentos'], 'FFD6001E');

  // Grand total
  const grandTotals = MESES.map((_, i) => opTotals[i] + empTotals[i]);
  const grandRow = wsFC.addRow([
    '═══ TOTAL SAÍDAS DE CAIXA',
    ...grandTotals,
    grandTotals.reduce((a,b)=>a+b,0)
  ]);
  grandRow.font = { bold: true, size: 12 };
  grandRow.eachCell((cell, colNumber) => {
    cell.fill = { type: 'pattern', pattern: 'solid', fgColor: { argb: 'FF1F4E79' } };
    cell.font = { bold: true, color: { argb: 'FFFFFFFF' }, size: 11 };
    if (colNumber > 1) cell.numFmt = numFmt;
  });

  console.log(`✅ FC_Direto gerado | Total: R$ ${grandTotals.reduce((a,b)=>a+b,0).toLocaleString('pt-BR',{minimumFractionDigits:2})}`);

  // Save
  await wb.xlsx.writeFile(XLSX_PATH);
  console.log(`\n🎉 Excel salvo com sucesso: ${XLSX_PATH}`);
  console.log(`   Abas adicionadas: DePara | APagar | FC_Direto`);
}

main().catch(err => { console.error('❌ Erro:', err.message); process.exit(1); });
